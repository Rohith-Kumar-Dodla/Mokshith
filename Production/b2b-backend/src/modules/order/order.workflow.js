import AppError from '../../errors/AppError.js';
import { ORDER_STATUS } from '../../constants/orderStatus.js';

const transitions = {
  [ORDER_STATUS.CREATED]: [
    ORDER_STATUS.PENDING_PAYMENT,
    ORDER_STATUS.PENDING,
    ORDER_STATUS.CONFIRMED,
    ORDER_STATUS.FAILED,
    ORDER_STATUS.CANCELLED,
  ],
  [ORDER_STATUS.PENDING_PAYMENT]: [
    ORDER_STATUS.CONFIRMED,
    ORDER_STATUS.FAILED,
    ORDER_STATUS.CANCELLED,
  ],
  [ORDER_STATUS.PENDING]: [ORDER_STATUS.CONFIRMED, ORDER_STATUS.CANCELLED, ORDER_STATUS.FAILED],
  [ORDER_STATUS.CONFIRMED]: [ORDER_STATUS.PROCESSING, ORDER_STATUS.PACKED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.PROCESSING]: [ORDER_STATUS.PACKED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.PACKED]: [ORDER_STATUS.READY_TO_DISPATCH, ORDER_STATUS.ASSIGNED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.READY_TO_DISPATCH]: [ORDER_STATUS.SHIPPED, ORDER_STATUS.ASSIGNED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.SHIPPED]: [ORDER_STATUS.OUT_FOR_DELIVERY, ORDER_STATUS.ASSIGNED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.ASSIGNED]: [ORDER_STATUS.ACCEPTED, ORDER_STATUS.CANCELLED, ORDER_STATUS.DELIVERY_FAILED],
  [ORDER_STATUS.ACCEPTED]: [ORDER_STATUS.OUT_FOR_PICKUP, ORDER_STATUS.PICKED_UP, ORDER_STATUS.CANCELLED, ORDER_STATUS.DELIVERY_FAILED],
  [ORDER_STATUS.OUT_FOR_PICKUP]: [ORDER_STATUS.PICKED_UP, ORDER_STATUS.CANCELLED, ORDER_STATUS.CUSTOMER_UNAVAILABLE],
  [ORDER_STATUS.PICKED_UP]: [ORDER_STATUS.OUT_FOR_DELIVERY, ORDER_STATUS.CANCELLED, ORDER_STATUS.DELIVERY_FAILED],
  [ORDER_STATUS.OUT_FOR_DELIVERY]: [
    ORDER_STATUS.DELIVERED,
    ORDER_STATUS.CANCELLED,
    ORDER_STATUS.DELIVERY_FAILED,
    ORDER_STATUS.CUSTOMER_UNAVAILABLE,
    ORDER_STATUS.REJECTED,
  ],
  [ORDER_STATUS.DELIVERED]: [ORDER_STATUS.COMPLETED, ORDER_STATUS.RETURNED],
  [ORDER_STATUS.COMPLETED]: [ORDER_STATUS.RETURNED],
  [ORDER_STATUS.RETURNED]: [ORDER_STATUS.REFUNDED],
  [ORDER_STATUS.DELIVERY_FAILED]: [ORDER_STATUS.ASSIGNED, ORDER_STATUS.CANCELLED, ORDER_STATUS.RETURNED],
  [ORDER_STATUS.CUSTOMER_UNAVAILABLE]: [ORDER_STATUS.OUT_FOR_DELIVERY, ORDER_STATUS.DELIVERY_FAILED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.REJECTED]: [ORDER_STATUS.RETURNED, ORDER_STATUS.CANCELLED],
  [ORDER_STATUS.CANCELLED]: [],
  [ORDER_STATUS.FAILED]: [],
  [ORDER_STATUS.REFUNDED]: [],
};

export const validateTransition = (current, next) => {
  if (!transitions[current] || !transitions[current].includes(next)) {
    throw new AppError(`Invalid status transition from ${current} to ${next}`, 400);
  }
};

export const getAllowedNextStatuses = (current) => transitions[current] || [];
